-- PostgreSQL schema. The database itself is created by the hosting provider.
CREATE SCHEMA IF NOT EXISTS dbo;

CREATE TABLE IF NOT EXISTS dbo.users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(180) NOT NULL UNIQUE,
    displayname varchar(80) NOT NULL,
    role varchar(20) NOT NULL CHECK (role IN ('Collector','Evaluator','Admin')),
    passwordsalt bytea NOT NULL,
    passwordhash bytea NOT NULL,
    phone varchar(40),
    deliveryaddress varchar(300),
    isactive boolean NOT NULL DEFAULT TRUE,
    createdat timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    bio varchar(500),
    avatarurl varchar(500),
    location varchar(80),
    website varchar(200)
);

CREATE TABLE IF NOT EXISTS dbo.categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(60) NOT NULL UNIQUE,
    isactive boolean NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS dbo.items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    categoryid integer NOT NULL REFERENCES dbo.categories(id),
    ownerid integer NOT NULL REFERENCES dbo.users(id),
    description varchar(1200),
    condition varchar(40),
    imageurl varchar(500),
    deliveryaddress varchar(300),
    phone varchar(40),
    status varchar(24) NOT NULL CHECK (status IN ('InCollection','ForTrade','Traded','PendingApproval','OnAuction','Sold')),
    createdat timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    auctionendsat timestamptz,
    CHECK ((status='OnAuction' AND auctionendsat IS NOT NULL) OR status<>'OnAuction')
);
CREATE INDEX IF NOT EXISTS ix_items_status_category ON dbo.items(status,categoryid);

CREATE TABLE IF NOT EXISTS dbo.tradeoffers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wanteditemid integer NOT NULL REFERENCES dbo.items(id),
    offereditemid integer NOT NULL REFERENCES dbo.items(id),
    senderid integer NOT NULL REFERENCES dbo.users(id),
    recipientid integer NOT NULL REFERENCES dbo.users(id),
    note varchar(500),
    status varchar(16) NOT NULL CHECK (status IN ('Pending','Accepted','Declined','Cancelled')),
    createdat timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (wanteditemid<>offereditemid)
);
CREATE INDEX IF NOT EXISTS ix_trades_pending_items ON dbo.tradeoffers(status,wanteditemid,offereditemid);

CREATE TABLE IF NOT EXISTS dbo.bids (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    itemid integer NOT NULL REFERENCES dbo.items(id),
    bidderid integer NOT NULL REFERENCES dbo.users(id),
    amount numeric(12,2) NOT NULL CHECK (amount>0),
    createdat timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_bids_item_amount ON dbo.bids(itemid,amount DESC,createdat);

CREATE TABLE IF NOT EXISTS dbo.messages (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    senderid integer NOT NULL REFERENCES dbo.users(id),
    recipientid integer NOT NULL REFERENCES dbo.users(id),
    itemid integer REFERENCES dbo.items(id),
    body varchar(2000) NOT NULL,
    sentat timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (senderid<>recipientid)
);
CREATE INDEX IF NOT EXISTS ix_messages_conversation ON dbo.messages(senderid,recipientid,sentat);

CREATE TABLE IF NOT EXISTS dbo.notifications (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipientid integer NOT NULL REFERENCES dbo.users(id) ON DELETE CASCADE,
    actorid integer,
    itemid integer,
    type varchar(32) NOT NULL,
    title varchar(120) NOT NULL,
    body varchar(300) NOT NULL,
    createdat timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    isread boolean NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS ix_notifications_recipient_read_created ON dbo.notifications(recipientid,isread,createdat DESC);

